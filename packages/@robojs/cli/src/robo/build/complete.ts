/**
 * Build Complete Hook
 *
 * Runs after Robo finishes building. Generates a standalone CLI entry point
 * from the routes manifest that Robo generated.
 */

import { promises as fs } from 'node:fs'
import path from 'node:path'
import type { BuildCompleteContext } from 'robo.js'

export default async function (context: BuildCompleteContext) {
	const { entries, logger, paths } = context

	// Get CLI command entries from the manifest via the entries API
	const cliEntries = entries.get('cli', 'cli') ?? []

	if (cliEntries.length === 0) {
		logger.debug('No CLI commands found, skipping entry point generation')
		return
	}

	logger.info(`Generating CLI entry point for ${cliEntries.length} command(s)...`)

	// Read package.json for CLI name/version
	let packageJson: { name?: string; version?: string; description?: string } = {}
	try {
		const pkgPath = path.join(paths.root, 'package.json')
		const content = await fs.readFile(pkgPath, 'utf-8')
		packageJson = JSON.parse(content)
	} catch {
		// Use defaults
	}

	const cliName = packageJson.name?.replace(/^@[^/]+\//, '') || 'cli'
	const cliVersion = packageJson.version || '1.0.0'
	const cliDescription = packageJson.description || ''

	// Generate imports and registrations
	const imports: string[] = []
	const registrations: string[] = []

	for (const entry of cliEntries) {
		const varName = `cmd_${entry.key.replace(/[^a-zA-Z0-9]/g, '_') || 'root'}`
		const importPath = './' + entry.path.replace(/\\/g, '/')

		imports.push(`import * as ${varName} from '${importPath}'`)

		if (!entry.key.includes(' ')) {
			registrations.push(`registerCommand(command, '${entry.key}', ${varName})`)
		} else {
			registrations.push(`registerNestedCommand(command, '${entry.key}', ${varName})`)
		}

		logger.debug(`  ${entry.key} ← ${entry.path}`)
	}

	const entryContent = `#!/usr/bin/env node
/**
 * Auto-generated CLI entry point
 * Generated by @robojs/cli
 */

import { Command } from 'robo.js/cli.js'

${imports.join('\n')}

const command = new Command('${cliName}')
command.version('${cliVersion}')
${cliDescription ? `command.description('${cliDescription.replace(/'/g, "\\'")}')` : ''}
command.option('-h', '--help', 'Shows this help menu')

function registerCommand(parent, name, mod) {
	const config = mod.config || {}
	const handler = mod.default ?? mod
	const sub = new Command(name)
	sub.description(config.description || '')
	sub.option('-h', '--help', 'Shows help for this command')
	if (config.options) {
		for (const opt of config.options) {
			sub.option(opt)
		}
	}
	if (config.positionalArgs) sub.positionalArgs(true)
	sub.handler(handler)
	parent.addCommand(sub)
	return sub
}

function registerNestedCommand(root, cmdPath, mod) {
	const parts = cmdPath.split(' ')
	let current = root
	for (let i = 0; i < parts.length - 1; i++) {
		const name = parts[i]
		let child = current.getChildCommands().find(c => c.getName() === name)
		if (!child) {
			child = new Command(name)
			child.option('-h', '--help', 'Shows help for this command')
			current.addCommand(child)
		}
		current = child
	}
	registerCommand(current, parts[parts.length - 1], mod)
}

${registrations.join('\n')}

command.parse()
`

	// Write entry point to build output
	const outputPath = path.join(paths.output, 'cli.js')
	await fs.writeFile(outputPath, entryContent, 'utf-8')

	// Make executable
	try {
		await fs.chmod(outputPath, 0o755)
	} catch {
		// Ignore on Windows
	}

	logger.ready(`CLI entry point generated: .robo/build/cli.js`)

	// Auto-set bin field if missing
	const pkgPath = path.join(paths.root, 'package.json')
	try {
		const rawContent = await fs.readFile(pkgPath, 'utf-8')
		const fullPkg = JSON.parse(rawContent)

		if (!fullPkg.bin) {
			// Detect indentation from the original file
			const indentMatch = rawContent.match(/\n([ \t]+)/)
			const indent = indentMatch?.[1] ?? '\t'

			fullPkg.bin = { [cliName]: '.robo/build/cli.js' }
			await fs.writeFile(pkgPath, JSON.stringify(fullPkg, null, indent) + '\n', 'utf-8')
			logger.info(`Added "bin" field to package.json — run "npm link" or "/cli link" during dev to test with your CLI name`)
		}
	} catch {
		// Non-critical — don't fail the build
	}
}
